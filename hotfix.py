def restore_original_gui_assets_from_git(root: Path) -> int:
    commits = []
    res_root = subprocess.run(
        ["git", "rev-list", "--max-parents=0", "HEAD"],
        cwd=str(root),
        capture_output=True,
        text=True,
    )
    if res_root.returncode == 0:
        for line in res_root.stdout.splitlines():
            if line.strip():
                commits.append(line.strip())

    for ref in ["origin/main", "origin/master", "HEAD", "HEAD~1", "HEAD~2", "HEAD~3"]:
        res = subprocess.run(
            ["git", "rev-parse", "--verify", ref],
            cwd=str(root),
            capture_output=True,
            text=True,
        )
        if res.returncode == 0:
            sha = res.stdout.strip()
            if sha not in commits:
                commits.append(sha)

    res_all = subprocess.run(
        ["git", "rev-list", "--reverse", "HEAD"],
        cwd=str(root),
        capture_output=True,
        text=True,
    )
    if res_all.returncode == 0:
        for line in res_all.stdout.splitlines():
            sha = line.strip()
            if sha and sha not in commits:
                commits.append(sha)

    if not commits:
        return 0

    valid_exts = {".png", ".jpg", ".jpeg", ".ttf", ".otf", ".fnt", ".json", ".glsl", ".fsh", ".vsh"}
    asset_commits = {}
    for sha in commits:
        ls_res = subprocess.run(
            ["git", "ls-tree", "-r", "--name-only", sha, "src/main/resources/assets"],
            cwd=str(root),
            capture_output=True,
            text=True,
        )
        if ls_res.returncode == 0:
            for line in ls_res.stdout.splitlines():
                rel_path = line.strip()
                if rel_path and Path(rel_path).suffix.lower() in valid_exts:
                    asset_commits.setdefault(rel_path, []).append(sha)

    restored_count = 0
    for rel_path, sha_list in sorted(asset_commits.items()):
        for sha in sha_list:
            sz_res = subprocess.run(
                ["git", "cat-file", "-s", f"{sha}:{rel_path}"],
                cwd=str(root),
                capture_output=True,
                text=True,
            )
            if sz_res.returncode != 0:
                continue
            try:
                blob_size = int(sz_res.stdout.strip())
            except ValueError:
                continue

            if blob_size <= 100 or blob_size == 9207:
                continue

            chk = subprocess.run(
                ["git", "checkout", sha, "--", rel_path],
                cwd=str(root),
                capture_output=True,
                text=True,
            )
            if chk.returncode == 0:
                restored_count += 1
                break

    return restored_count


def fix_attrium_logo_without_touching_icons(root: Path) -> int:
    logo_bytes = base64.b64decode(ATTRIUM_LOGO_RGBA_B64)
    assets_root = root / "src/main/resources/assets"
    fixed = 0

    mod_icon = assets_root / "releon/ui/icon.png"
    if not mod_icon.with_suffix(".json").exists():
        mod_icon.parent.mkdir(parents=True, exist_ok=True)
        mod_icon.write_bytes(logo_bytes)
        fixed += 1

    if assets_root.is_dir():
        for png_file in assets_root.rglob("*.png"):
            if png_file == mod_icon:
                continue
            if png_file.with_suffix(".json").exists() or png_file.with_suffix(".fnt").exists():
                continue
            raw = png_file.read_bytes() if png_file.is_file() else b""
            is_disguised_jpeg = raw.startswith(b"\xff\xd8\xff")
            is_exact_logo_name = png_file.stem.lower() in {"logo", "attrium", "attrium_logo", "client_logo"}
            if is_disguised_jpeg or is_exact_logo_name:
                png_file.write_bytes(logo_bytes)
                fixed += 1

    return fixed


def unwrap_for_loops_in_module_option(text: str) -> str:
    pattern = re.compile(r"([ \t]*)if\s*\(\s*(?:this\.)?module\.isExpanded\(\)\s*\)\s*\{\n([ \t]*for\s*\()", re.M)
    while True:
        m = pattern.search(text)
        if not m:
            break
        if_start = m.start()
        brace_open = text.find("{", if_start)
        depth = 0
        i = brace_open
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    inner = text[brace_open + 1:i]
                    if inner.startswith("\n"):
                        inner = inner[1:]
                    if inner.endswith("\n" + m.group(1)):
                        inner = inner[:-len("\n" + m.group(1))]
                    elif inner.endswith("\n"):
                        inner = inner[:-1]
                    text = text[:if_start] + inner + text[i + 1:]
                    break
            i += 1
        else:
            break
    return text


def wrap_render_height_and_input_for_loops_in_module_option(text: str) -> str:
    """
    Unwraps any previous `if (this.module.isExpanded())` blocks, and then wraps ONLY
    `for (...)` loops in ModuleOption.java that are NOT in the constructor AND do NOT
    call `.add(` or `.getSettings(` (so setting component creation/population is NEVER skipped!).
    """
    text = unwrap_for_loops_in_module_option(text)

    ctor_ranges = []
    for m in re.finditer(r"\bModuleOption\s*\([^)]*\)\s*\{", text):
        start = m.start()
        brace_start = text.find("{", m.end() - 1)
        depth = 0
        i = brace_start
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    ctor_ranges.append((start, i + 1))
                    break
            i += 1

    def in_ctor(pos: int) -> bool:
        return any(s <= pos < e for s, e in ctor_ranges)

    out = []
    idx = 0
    for_pattern = re.compile(r"(^[ \t]*)for\s*\(", re.M)

    while idx < len(text):
        m = for_pattern.search(text, idx)
        if not m:
            out.append(text[idx:])
            break

        for_start = m.start()
        indent = m.group(1)
        if in_ctor(for_start):
            out.append(text[idx:m.end()])
            idx = m.end()
            continue

        paren_start = text.find("(", m.start())
        p_depth = 0
        j = paren_start
        while j < len(text):
            if text[j] == "(":
                p_depth += 1
            elif text[j] == ")":
                p_depth -= 1
                if p_depth == 0:
                    break
            j += 1

        if j >= len(text):
            out.append(text[idx:])
            break

        k = j + 1
        while k < len(text) and text[k] in " \t\r\n":
            k += 1

        if k >= len(text) or text[k] != "{":
            out.append(text[idx:k])
            idx = k
            continue

        b_depth = 0
        end_brace = k
        while end_brace < len(text):
            if text[end_brace] == "{":
                b_depth += 1
            elif text[end_brace] == "}":
                b_depth -= 1
                if b_depth == 0:
                    break
            end_brace += 1

        if end_brace >= len(text):
            out.append(text[idx:])
            break

        for_block = text[for_start:end_brace + 1]

        # CRITICAL: Never wrap a loop that populates components (`.add(` or `getSettings(`)
        if ".add(" in for_block or "getSettings(" in for_block or "getGuiSettings(" in for_block:
            out.append(text[idx:end_brace + 1])
            idx = end_brace + 1
            continue

        out.append(text[idx:for_start])
        wrapped = (
            f"{indent}if (this.module.isExpanded()) {{\n"
            f"{for_block}\n"
            f"{indent}}}"
        )
        out.append(wrapped)
        idx = end_brace + 1

    return "".join(out)


